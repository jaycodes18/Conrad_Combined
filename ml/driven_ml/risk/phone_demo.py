"""Export the Driven ML synthetic warning replays consumed by the Expo phone app."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from ..workspace import write_text_atomic
from .fixtures import CASES, FIXTURES_DIR, FixtureCase, iter_case_signals
from .signal import DriverRiskSignal

DEMO_CASES = {"drowsy": "eye-closure", "distracted": "head-away"}
REPLAY_START_SECONDS = 148.0
REPLAY_SAMPLE_SECONDS = 0.5


def replay(case: FixtureCase) -> list[DriverRiskSignal]:
    snapshots: list[DriverRiskSignal] = []
    next_sample = REPLAY_START_SECONDS
    for signal in iter_case_signals(case):
        if signal.t_seconds < REPLAY_START_SECONDS:
            continue
        if case.pick(signal):
            snapshots.append(signal)
            return snapshots
        if signal.t_seconds >= next_sample:
            snapshots.append(signal)
            next_sample += REPLAY_SAMPLE_SECONDS
    raise RuntimeError(f"phone demo {case.name}: no warning in the replay")


def render_replays() -> str:
    lines = [
        "// Generated by driven_ml.risk.phone_demo. Do not edit by hand.",
        "import type { DriverRiskSignal } from './driverRiskSignal';",
        "",
        "export const drivenMlReplays: Record<'eye-closure' | 'head-away', readonly DriverRiskSignal[]> = {",
    ]
    for case in CASES:
        if case.name not in DEMO_CASES:
            continue
        lines.append(f"  '{DEMO_CASES[case.name]}': [")
        for signal in replay(case):
            lines.append(f"    {json.dumps(signal.to_json(), ensure_ascii=False)},")
        lines.append("  ],")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app-dir", type=Path, required=True, help="Path to the Conrad-Challenge-App checkout")
    parser.add_argument("--check", action="store_true", help="Check that the app has the current export")
    args = parser.parse_args(argv)
    if not (args.app_dir / "App.tsx").is_file():
        parser.error("--app-dir must be the Conrad-Challenge-App directory containing App.tsx")

    output = args.app_dir / "src" / "drivenMl"
    contract = FIXTURES_DIR.parent / "driver_risk_signal.v1.ts"
    documents = {"driverRiskSignal.ts": contract.read_text(encoding="utf-8"), "replays.ts": render_replays()}
    for name, contents in documents.items():
        path = output / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != contents:
                parser.exit(1, f"Phone demo export is missing or stale: {path}\n")
        else:
            write_text_atomic(path, contents)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
